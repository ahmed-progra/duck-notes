package app.duck.notes.data.local

import android.content.Context
import android.util.Log
import androidx.room.Room
import androidx.test.core.app.ApplicationProvider
import androidx.test.ext.junit.runners.AndroidJUnit4
import app.duck.notes.data.local.dao.NoteDao
import app.duck.notes.data.local.dao.TagDao
import app.duck.notes.data.local.entity.NoteEntity
import androidx.sqlite.driver.bundled.BundledSQLiteDriver
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.runBlocking
import org.junit.After
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith
import java.util.UUID
import kotlin.system.measureTimeMillis

/**
 * Verifies the FTS5 external-content triggers stay in sync with `notes`, that tag filtering works,
 * and logs perf at 5000 notes. Perf is measured + logged, not hard-asserted, so the suite doesn't
 * flake on slow emulators — eyeball the logged numbers against the < 50 ms / < 30 ms targets.
 *
 * `perf_at5000Notes` times **both** tag queries. Filtering by id uses the index on `note_tags`;
 * filtering by path cannot, because `substr(t.name, 1, …)` is a function on the column and no index
 * serves it. That was a deliberate trade — `tags` is the smallest table in the schema — and the
 * by-path number is the tripwire on it. If it ever crosses 30 ms, the KDoc on `notesByTagPath` says
 * what moving to `LIKE` would owe: an `ESCAPE` clause, because `isTagChar` permits `_`.
 */
@RunWith(AndroidJUnit4::class)
class DuckDatabaseTest {

    private lateinit var db: DuckDatabase
    private lateinit var notes: NoteDao
    private lateinit var tags: TagDao

    @Before
    fun setUp() {
        val context = ApplicationProvider.getApplicationContext<Context>()
        db = Room.inMemoryDatabaseBuilder(context, DuckDatabase::class.java)
            // Must match production: system SQLite may lack FTS5, which `notes_fts` requires.
            .setDriver(BundledSQLiteDriver())
            .addCallback(DuckDatabaseCallback(seedSampleNotes = false))
            .build()
        notes = db.noteDao()
        tags = db.tagDao()
    }

    @After
    fun tearDown() = db.close()

    private fun note(title: String, body: String) =
        NoteEntity(
            id = UUID.randomUUID().toString(),
            title = title,
            body = body,
            createdAt = 0L,
            modifiedAt = 0L,
        )

    @Test
    fun insert_isFoundByFts() = runBlocking {
        notes.saveNoteWithTags(note("Kingfisher", "a small diving bird"), emptyList())

        assertEquals(1, notes.search("kingfisher").size)
        assertEquals(1, notes.search("diving").size) // matches body too
        assertTrue(notes.search("penguin").isEmpty())
    }

    @Test
    fun update_movesFtsTerm() = runBlocking {
        val original = note("mallard", "duck body")
        val rowid = notes.insert(original)
        assertEquals(1, notes.search("mallard").size)

        notes.update(original.copy(rowid = rowid, title = "teal"))

        assertTrue("old title term must be gone", notes.search("mallard").isEmpty())
        assertEquals("new title term must be found", 1, notes.search("teal").size)
    }

    @Test
    fun delete_removesFromFts() = runBlocking {
        val n = note("heron", "wading bird")
        notes.insert(n)
        assertEquals(1, notes.search("heron").size)

        // delete matches by rowid; re-read the stored row to get its assigned rowid
        val stored = notes.observeNotes().first().single()
        notes.delete(stored)

        assertTrue(notes.search("heron").isEmpty())
    }

    /**
     * The upsert branch of [NoteDao.saveNoteWithTags]. Room keys `@Update`/`@Upsert` off the primary
     * key, which here is the autogenerated rowid, not the app-facing `id` — so a second save of the
     * same note is where a duplicate row, a tripped unique index, or a desynced FTS entry would show
     * up. Every other test in this class only exercises the insert branch.
     */
    @Test
    fun saveNoteWithTags_secondSaveUpdatesInPlace() = runBlocking {
        val original = note("first", "body one")
        notes.saveNoteWithTags(original, listOf("alpha"))

        notes.saveNoteWithTags(original.copy(title = "second", body = "body two"), listOf("beta"))

        assertEquals("second save must update, not insert", 1, notes.count())
        val stored = notes.observeNotes().first().single()
        assertEquals("second", stored.title)
        assertEquals(original.id, stored.id)

        assertTrue("old title term must leave the FTS index", notes.search("first").isEmpty())
        assertEquals("new title term must be indexed", 1, notes.search("second").size)
        assertEquals("new body term must be indexed", 1, notes.search("two").size)

        val remaining = tags.observeAll().first().map { it.name }.toSet()
        assertEquals("tags must be rewired and the orphan dropped", setOf("beta"), remaining)
    }

    @Test
    fun trashedNotesAreExcludedFromSearch() = runBlocking {
        notes.saveNoteWithTags(note("Grebe", "trashed").copy(isTrashed = true), emptyList())
        assertTrue(notes.search("grebe").isEmpty())
    }

    @Test
    fun tagFilter_returnsOnlyTaggedNotes() = runBlocking {
        notes.saveNoteWithTags(note("A", "work note"), listOf("work"))
        notes.saveNoteWithTags(note("B", "home note"), listOf("home"))

        val workTagId = tags.observeAll().first().single { it.name == "work" }.id
        val result = notes.notesByTag(workTagId).first()

        assertEquals(1, result.size)
        assertEquals("A", result.single().title)
    }

    @Test
    fun orphanCleanupSkipsPinnedButRemovesPlainTags() = runBlocking {
        // One note owns both tags; deleting it cascades away both cross-refs -> both orphaned.
        val owner = note("C", "temp")
        notes.saveNoteWithTags(owner, listOf("keepme", "dropme"))
        val keep = tags.observeAll().first().single { it.name == "keepme" }
        tags.upsert(keep.copy(isPinned = true)) // user pins one of them

        val stored = notes.observeNotes().first().single { it.id == owner.id }
        notes.delete(stored) // FK cascade removes both note_tags rows

        // Any subsequent save runs orphan cleanup.
        notes.saveNoteWithTags(note("D", "y"), emptyList())

        val remaining = tags.observeAll().first().map { it.name }.toSet()
        assertTrue("pinned orphan must survive", "keepme" in remaining)
        assertTrue("plain orphan must be removed", "dropme" !in remaining)
    }

    @Test
    fun perf_at5000Notes() = runBlocking {
        // A real search matches a small subset, so only every NEEDLE_EVERY-th note carries the rare
        // token. Searching a token present in every row would time a full-table scan and sort
        // instead of an index lookup.
        // insertAll is one Room transaction; room-ktx withTransaction can't be used here because
        // it goes through the SupportSQLite path, which a SQLiteDriver replaces.
        notes.insertAll(
            List(COUNT) { i ->
                val body = if (i % NEEDLE_EVERY == 0) "needle body token$i" else "filler body token$i"
                note("Note $i", body)
            },
        )
        notes.saveNoteWithTags(note("tagged", "filler body"), listOf("bulk"))
        // A nested tag so the prefix query below has a descendant to find and a DISTINCT to do.
        notes.saveNoteWithTags(note("nested", "filler body"), listOf("bulk/child"))
        notes.saveNoteWithTags(note("both", "filler body"), listOf("bulk", "bulk/child"))
        val bulkTagId = tags.observeAll().first().single { it.name == "bulk" }.id

        val ftsMs = measureTimeMillis { notes.search("needle") }
        val tagMs = measureTimeMillis { notes.notesByTag(bulkTagId).first() }
        val pathMs = measureTimeMillis { notes.notesByTagPath("bulk").first() }

        val matches = notes.search("needle").size
        val pathRows = notes.notesByTagPath("bulk").first().size
        Log.i(
            TAG,
            "FTS query over $COUNT notes matched $matches rows = $ftsMs ms (target < 50); " +
                "tag filter by id = $tagMs ms (target < 30); " +
                "tag filter by PATH matched $pathRows rows = $pathMs ms (target < 30)",
        )
        assertEquals("fixture must be selective", COUNT / NEEDLE_EVERY, matches)
        // The note carrying both `bulk` and `bulk/child` must appear once, not twice — that is the
        // DISTINCT, and it is the cheap-implementation bug the with-descendants count was written
        // to avoid. Asserted; the timings above are logged only, per this file's convention.
        assertEquals("prefix query must dedupe", 3, pathRows)
    }

    private companion object {
        const val COUNT = 5000

        /** Every Nth note carries the searched token, keeping the perf query selective. */
        const val NEEDLE_EVERY = 1000
        const val TAG = "DuckDatabaseTest"
    }
}
